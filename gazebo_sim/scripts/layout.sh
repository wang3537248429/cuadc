#!/usr/bin/env bash

# 仿真目录本身就是完整项目根，不再依赖仓库顶层的共享 src/models。
CUADC_SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
CUADC_PROJECT_DIR="$(cd -- "$CUADC_SCRIPT_DIR/.." && pwd)"
CUADC_GAZEBO_DIR="$CUADC_PROJECT_DIR"
CUADC_SIM_CONFIG_DIR="$CUADC_GAZEBO_DIR/config"
CUADC_SIM_DOCS_DIR="$CUADC_GAZEBO_DIR/docs"
CUADC_SIM_REQUIREMENTS="$CUADC_GAZEBO_DIR/requirements.txt"

export CUADC_PROJECT_DIR CUADC_GAZEBO_DIR CUADC_SIM_CONFIG_DIR
export CUADC_SIM_DOCS_DIR CUADC_SIM_REQUIREMENTS
